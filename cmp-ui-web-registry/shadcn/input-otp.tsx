import * as React from "react";
import { MinusIcon } from "lucide-react";
import { cn } from "cn";
import { OTPInput, OTPInputContext } from "input-otp";

function InputOTP({
  className,
  containerClassName,
  ...props
}: React.ComponentProps<typeof OTPInput> & {
  containerClassName?: string;
}) {
  return (
    <OTPInput
      data-slot="input-otp"
      containerClassName={cn(
        "cn-input-otp flex items-center has-disabled:opacity-[var(--ien-state-disabled-alpha)]",
        containerClassName,
      )}
      spellCheck={false}
      className={cn("disabled:cursor-not-allowed", className)}
      {...props}
    />
  );
}

function InputOTPGroup({ className, ...props }: React.ComponentProps<"div">) {
  return (
    <div
      data-slot="input-otp-group"
      className={cn(
        "flex items-center rounded-[var(--ien-control-radius-base)] has-aria-invalid:border-ien-danger has-aria-invalid:ring-[length:var(--ien-control-focus-ring-width)] has-aria-invalid:ring-ien-danger/20 dark:has-aria-invalid:ring-ien-danger/40",
        className,
      )}
      {...props}
    />
  );
}

function InputOTPSlot({
  index,
  className,
  ...props
}: React.ComponentProps<"div"> & {
  index: number;
}) {
  const inputOTPContext = React.useContext(OTPInputContext);
  const { char, hasFakeCaret, isActive } = inputOTPContext?.slots[index] ?? {};

  return (
    <div
      data-slot="input-otp-slot"
      data-active={isActive}
      className={cn(
        "relative flex size-8 items-center justify-center border-y border-r border-ien-surface-variant text-ien-body2 transition-all outline-none first:rounded-l-[var(--ien-control-radius-base)] first:border-l last:rounded-r-[var(--ien-control-radius-base)] aria-invalid:border-ien-danger data-[active=true]:z-10 data-[active=true]:border-ien-brand data-[active=true]:ring-[length:var(--ien-control-focus-ring-width)] data-[active=true]:ring-ien-brand/50 data-[active=true]:aria-invalid:border-ien-danger data-[active=true]:aria-invalid:ring-ien-danger/20 dark:bg-ien-surface-variant/30 dark:data-[active=true]:aria-invalid:ring-ien-danger/40",
        className,
      )}
      {...props}
    >
      {char}
      {hasFakeCaret && (
        <div className="pointer-events-none absolute inset-0 flex items-center justify-center">
          <div className="h-4 w-px animate-caret-blink bg-ien-text-primary duration-1000" />
        </div>
      )}
    </div>
  );
}

function InputOTPSeparator({ ...props }: React.ComponentProps<"div">) {
  return (
    <div
      data-slot="input-otp-separator"
      className="flex items-center [&_svg:not([class*='size-'])]:size-4"
      role="separator"
      {...props}
    >
      <MinusIcon />
    </div>
  );
}

export { InputOTP, InputOTPGroup, InputOTPSlot, InputOTPSeparator };
